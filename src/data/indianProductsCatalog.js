/**
 * Quick lookup in Indian Products Catalog
 * Matches on exact barcode, configured aliases, or 12-digit prefix (resilient to minor check-digit scanner noise)
 */
export function findInIndianCatalog(barcode) {
  if (!barcode) return null;
  const clean = String(barcode).trim();

  // 1. Exact match
  const exact = indianProductsCatalog.find((p) => p.barcode === clean || (p.aliases && p.aliases.includes(clean)));
  if (exact) return exact;

  // 2. Resilient 12-digit prefix match (EAN-13 GS1 Company & Item Reference)
  if (clean.length === 13) {
    const prefix12 = clean.substring(0, 12);
    const prefixMatch = indianProductsCatalog.find((p) => p.barcode.substring(0, 12) === prefix12);
    if (prefixMatch) return prefixMatch;
  }

  return null;
}
